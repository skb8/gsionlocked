        f'#define SM_ENTRY_BYTES {meta["source_bytes"]}\n#define SM_ENTRY_SOURCE_SHA "{meta["source_sha256"]}"\n#define SM_ENTRY_PATCHED_SHA "{meta["patched_sha256"]}"\n'
