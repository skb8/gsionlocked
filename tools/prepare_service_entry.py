def adapt(source,kind='servicemanager'):
    if kind not in ['servicemanager','hwservicemanager']:raise ValueError('Unsupported service')
    hardware=kind=='hwservicemanager'
    source_sha=HW_SOURCE_SHA if hardware else SOURCE_SHA
    source_bytes=120312 if hardware else 137200
    if len(source)!=source_bytes or hashlib.sha256(source).hexdigest()!=source_sha:raise ValueError('Not the pinned GSI servicemanager')
